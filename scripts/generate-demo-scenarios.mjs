#!/usr/bin/env node
/**
 * Generate platform DemoScenarios from samples/scenarios.json.
 * Run: node scripts/generate-demo-scenarios.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const catalog = JSON.parse(
  readFileSync(join(root, 'samples/scenarios.json'), 'utf8'),
);

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function kotlinStringMap(obj) {
  if (!obj || Object.keys(obj).length === 0) return 'emptyMap()';
  const entries = Object.entries(obj)
    .map(([k, v]) => `"${esc(k)}" to "${esc(v)}"`)
    .join(', ');
  return `mapOf(${entries})`;
}

function swiftStringDict(obj) {
  if (!obj || Object.keys(obj).length === 0) return '[:]';
  const entries = Object.entries(obj)
    .map(([k, v]) => `"${esc(k)}": "${esc(v)}"`)
    .join(', ');
  return `[${entries}]`;
}

function dartStringMap(obj) {
  if (!obj || Object.keys(obj).length === 0) return 'const {}';
  const entries = Object.entries(obj)
    .map(([k, v]) => `'${esc(k)}': '${esc(v)}'`)
    .join(', ');
  return `{${entries}}`;
}

function genKotlin() {
  const cases = catalog.scenarios
    .map((s) => {
      const headers = kotlinStringMap(s.headers);
      const body = s.body != null ? `"${esc(s.body)}"` : 'null';
      const contentType =
        s.contentType != null ? `"${esc(s.contentType)}"` : 'null';
      const responseKind =
        s.responseKind != null ? `"${esc(s.responseKind)}"` : 'null';
      const logLevel = s.logLevel != null ? `"${esc(s.logLevel)}"` : 'null';
      const logMessage = s.logMessage != null ? `"${esc(s.logMessage)}"` : 'null';
      const logTag = s.logTag != null ? `"${esc(s.logTag)}"` : 'null';
      const method = s.method != null ? `"${esc(s.method)}"` : 'null';
      const url = s.url != null ? `"${esc(s.url)}"` : 'null';
      return `        DemoScenario(
            id = "${esc(s.id)}",
            label = "${esc(s.label)}",
            description = "${esc(s.description)}",
            kind = "${esc(s.kind)}",
            method = ${method},
            url = ${url},
            headers = ${headers},
            contentType = ${contentType},
            body = ${body},
            responseKind = ${responseKind},
            logLevel = ${logLevel},
            logMessage = ${logMessage},
            logTag = ${logTag},
        )`;
    })
    .join(',\n');

  return `// GENERATED by scripts/generate-demo-scenarios.mjs — do not edit.
package io.mocklane.sample.demo

data class DemoScenario(
    val id: String,
    val label: String,
    val description: String,
    val kind: String,
    val method: String?,
    val url: String?,
    val headers: Map<String, String>,
    val contentType: String?,
    val body: String?,
    val responseKind: String?,
    val logLevel: String?,
    val logMessage: String?,
    val logTag: String?,
)

object DemoScenarios {
    val all: List<DemoScenario> = listOf(
${cases}
    )

    fun byId(id: String): DemoScenario? = all.find { it.id == id }
}
`;
}

function genSwift() {
  const cases = catalog.scenarios
    .map((s) => {
      const headers = swiftStringDict(s.headers);
      const body = s.body != null ? `"${esc(s.body)}"` : 'nil';
      const contentType =
        s.contentType != null ? `"${esc(s.contentType)}"` : 'nil';
      const responseKind =
        s.responseKind != null ? `"${esc(s.responseKind)}"` : 'nil';
      const logLevel = s.logLevel != null ? `"${esc(s.logLevel)}"` : 'nil';
      const logMessage = s.logMessage != null ? `"${esc(s.logMessage)}"` : 'nil';
      const logTag = s.logTag != null ? `"${esc(s.logTag)}"` : 'nil';
      const method = s.method != null ? `"${esc(s.method)}"` : 'nil';
      const url = s.url != null ? `"${esc(s.url)}"` : 'nil';
      return `        DemoScenario(
            id: "${esc(s.id)}",
            label: "${esc(s.label)}",
            description: "${esc(s.description)}",
            kind: "${esc(s.kind)}",
            method: ${method},
            url: ${url},
            headers: ${headers},
            contentType: ${contentType},
            body: ${body},
            responseKind: ${responseKind},
            logLevel: ${logLevel},
            logMessage: ${logMessage},
            logTag: ${logTag}
        )`;
    })
    .join(',\n');

  return `// GENERATED by scripts/generate-demo-scenarios.mjs — do not edit.
import Foundation

struct DemoScenario: Identifiable {
    let id: String
    let label: String
    let description: String
    let kind: String
    let method: String?
    let url: String?
    let headers: [String: String]
    let contentType: String?
    let body: String?
    let responseKind: String?
    let logLevel: String?
    let logMessage: String?
    let logTag: String?
}

enum DemoScenarios {
    static let all: [DemoScenario] = [
${cases}
    ]

    static func byId(_ id: String) -> DemoScenario? {
        all.first { $0.id == id }
    }
}
`;
}

function genDart() {
  const dartStr = (val) => {
    if (val == null) return 'null';
    return `'${esc(val).replace(/'/g, "\\'")}'`;
  };

  const cases = catalog.scenarios
    .map((s) => {
      const headers = dartStringMap(s.headers);
      return [
        '    DemoScenario(',
        `      id: ${dartStr(s.id)},`,
        `      label: ${dartStr(s.label)},`,
        `      description: ${dartStr(s.description)},`,
        `      kind: ${dartStr(s.kind)},`,
        `      method: ${dartStr(s.method)},`,
        `      url: ${dartStr(s.url)},`,
        `      headers: ${headers},`,
        `      contentType: ${dartStr(s.contentType)},`,
        `      body: ${dartStr(s.body)},`,
        `      responseKind: ${dartStr(s.responseKind)},`,
        `      logLevel: ${dartStr(s.logLevel)},`,
        `      logMessage: ${dartStr(s.logMessage)},`,
        `      logTag: ${dartStr(s.logTag)},`,
        '    )',
      ].join('\n');
    })
    .join(',\n');

  return `// GENERATED by scripts/generate-demo-scenarios.mjs — do not edit.

class DemoScenario {
  const DemoScenario({
    required this.id,
    required this.label,
    required this.description,
    required this.kind,
    this.method,
    this.url,
    this.headers = const {},
    this.contentType,
    this.body,
    this.responseKind,
    this.logLevel,
    this.logMessage,
    this.logTag,
  });

  final String id;
  final String label;
  final String description;
  final String kind;
  final String? method;
  final String? url;
  final Map<String, String> headers;
  final String? contentType;
  final String? body;
  final String? responseKind;
  final String? logLevel;
  final String? logMessage;
  final String? logTag;
}

class DemoScenarios {
  static const List<DemoScenario> all = [
${cases}
  ];

  static DemoScenario? byId(String id) {
    for (final s in all) {
      if (s.id == id) return s;
    }
    return null;
  }
}
`;
}

const outputs = [
  {
    path: 'samples/android/app/src/main/java/io/mocklane/sample/demo/DemoScenarios.kt',
    content: genKotlin(),
  },
  { path: 'samples/ios/App/DemoScenarios.swift', content: genSwift() },
  { path: 'samples/flutter/lib/demo_scenarios.dart', content: genDart() },
  { path: 'samples/swift-cli/Sources/DemoScenarios.swift', content: genSwift() },
];

for (const { path, content } of outputs) {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content, 'utf8');
  console.log('wrote', path);
}

console.log(`Generated ${catalog.scenarios.length} scenarios.`);
